# 집합 기초

# ===========================================================
#  집합 (set): 여러 객체를 순서 없이 중복을 허용하지 않고 저장하는 변경 가능한 자료형
#  집합의 특징
#  1. ( mutable, 변경 가능 )
#  2. ( iterable, 반복 가능 )
#  3. ( seqence X, 인덱싱과 슬라이싱 불가 )
#  4. ( 중복 허용 안함 )
# ===========================================================

# 집합 생성
a = {}  # 딕셔너리
a = set()  # 집합
print(type(a))

a = {1, 2, 5, 7, 8}
print(a)

b = {1, 5, 3, 2, 6, 2, 7}
print(b)

# ===========================================================
# 1. 집합은 mutable하다. (변경 가능)
# ===========================================================

a.update({3, 4})
print(a)

a.pop()  # 거의 랜덤
print(a)

a.remove(3)
print(a)

# ===========================================================
# 2. 집합은 iterable하다. (반복 가능)
# ===========================================================

# 집합 순회
for x in a:
    print(x)

# ===========================================================
# 3. 집합은 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================

# a[0] = 100 불가

# ===========================================================
# 4. 집합은 중복을 허용하지 않는다.
# ===========================================================

s = {10, 10, 20, 20, 30}
print(s)

# ===========================================================
#  파이썬 내장 함수
# ===========================================================

print(len(s))
print(sum(s))
print(min(s), max(s))

# 집합 합치기
s2 = {40, 50}
s.update(s2)  # print(s + s2) 불가능
print(s)

s = {10, 10, 20, 20, 30}

print(s.union(s2))
print(s)

# 집합 반복하기
# print(s * 2) 불가능

# 멤버십 연산자
print(10 in s)
print(1 in s)
